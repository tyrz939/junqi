// Known answers for jane-core's Sfc32, from the TypeScript generator (jane/src/sim/rng.ts copied
// verbatim below so this runs under plain node). Writes crates/jane-core/src/rng_vectors.rs.
import { writeFileSync } from "node:fs";

function rngSeed(seed, stream = 0) {
  let h = (seed ^ Math.imul(stream + 1, 0x9e3779b9)) >>> 0;
  const next = () => {
    h = (h + 0x9e3779b9) >>> 0;
    let z = h;
    z = Math.imul(z ^ (z >>> 16), 0x21f0aaad);
    z = Math.imul(z ^ (z >>> 15), 0x735a2d97);
    return (z ^ (z >>> 15)) >>> 0;
  };
  const s = [next(), next(), next(), next()];
  for (let i = 0; i < 12; i++) rngU32(s);
  return s;
}
function rngU32(s) {
  const t = (((s[0] + s[1]) >>> 0) + s[3]) >>> 0;
  s[3] = (s[3] + 1) >>> 0;
  s[0] = (s[1] ^ (s[1] >>> 9)) >>> 0;
  s[1] = (s[2] + (s[2] << 3)) >>> 0;
  s[2] = ((s[2] << 21) | (s[2] >>> 11)) >>> 0;
  s[2] = (s[2] + t) >>> 0;
  return t;
}
function mix32(h) {
  h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  return (h ^ (h >>> 16)) >>> 0;
}
const cases = [[0, 0], [1, 0], [1, 1], [42, 0], [2026, 7], [0xffffffff, 0], [123456789, 100], [7, 12]];
let out = "// Generated by tools/gen/rng-vectors.mjs from the TypeScript generator. Do not edit.\n\n";
out += "/// `(seed, stream, first eight next_u32)`.\n";
out += "pub(crate) static VECTORS: &[(u32, u32, [u32; 8])] = &[\n";
for (const [seed, stream] of cases) {
  const s = rngSeed(seed, stream);
  const v = Array.from({ length: 8 }, () => rngU32(s));
  out += `    (${seed >>> 0}, ${stream}, [${v.join(", ")}]),\n`;
}
out += "];\n\n";
out += "/// `(input, mix32(input))` from jane/src/world/kit.ts.\n";
out += "pub(crate) static MIX32: &[(u32, u32)] = &[\n";
for (const x of [0, 1, 2, 0xdeadbeef, 0x9e3779b9, 0xffffffff]) out += `    (${x >>> 0}, ${mix32(x)}),\n`;
out += "];\n";
writeFileSync(new URL("../../crates/jane-core/src/rng_vectors.rs", import.meta.url), out);
