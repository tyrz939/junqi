#!/usr/bin/env python3
"""Emit crates/jane-core/src/trig_table.rs: the integer tables Angle reads (ARCHITECTURE.md §2).

Run once; the output is committed. The tables are data, so every target reads the same integers
and no float ever reaches jane-core.
"""
import math, pathlib

out = pathlib.Path(__file__).resolve().parents[2] / "crates/jane-core/src/trig_table.rs"
# Quarter wave of sine at 4096 steps per turn, Q15 (32768 = 1.0).
sin_q = [round(math.sin(i * 2 * math.pi / 4096) * 32768) for i in range(1025)]
# atan(t / 256) for t in 0..=256, in Angle units (65536 per turn): 0..=8192.
atan = [round(math.atan(t / 256) * 65536 / (2 * math.pi)) for t in range(257)]

def rows(vals, per=16):
    return "\n".join("    " + " ".join(f"{v}," for v in vals[i:i + per]) for i in range(0, len(vals), per))

out.write_text(f"""// Generated by tools/gen/trig.py. Do not edit.

/// sin at `i * 2π / 4096` for `i` in `0..=1024`, Q15 (32768 = 1.0). The other three quarters by symmetry.
pub(crate) static SIN_QUARTER: [u16; 1025] = [
{rows(sin_q)}
];

/// atan(t / 256) for `t` in `0..=256`, in `Angle` units (65536 per turn), so 0..=8192.
pub(crate) static ATAN: [u16; 257] = [
{rows(atan)}
];
""")
print("wrote", out)
